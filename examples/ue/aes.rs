impl_resolver!(PEImage, AESKeys, |ctx| async {
    use binary_bloodhound::BinaryMatcher;

    let patterns = [
        "C7 45 D0 [ ?? ?? ?? ?? ] C7 45 D4 [ ?? ?? ?? ?? ] ?? ?? ?? ?? C7 45 D8 [ ?? ?? ?? ?? ] C7 45 DC [ ?? ?? ?? ?? ] C7 45 E0 [ ?? ?? ?? ?? ] C7 45 E4 [ ?? ?? ?? ?? ] C7 45 E8 [ ?? ?? ?? ?? ] C7 45 EC [ ?? ?? ?? ?? ]",
        "C7 01 [ ?? ?? ?? ?? ] C7 41 04 [ ?? ?? ?? ?? ] C7 41 08 [ ?? ?? ?? ?? ] C7 41 0C [ ?? ?? ?? ?? ] C7 41 10 [ ?? ?? ?? ?? ] C7 41 14 [ ?? ?? ?? ?? ] C7 41 18 [ ?? ?? ?? ?? ] C7 41 1C [ ?? ?? ?? ?? ] C3",
        "C7 45 D0 [ ?? ?? ?? ?? ] C7 45 D4 [ ?? ?? ?? ?? ] C7 45 D8 [ ?? ?? ?? ?? ] C7 45 DC [ ?? ?? ?? ?? ] 0F 10 45 D0 C7 45 E0 [ ?? ?? ?? ?? ] C7 45 E4 [ ?? ?? ?? ?? ] C7 45 E8 [ ?? ?? ?? ?? ] C7 45 EC [ ?? ?? ?? ?? ]",
    ];

    BinaryMatcher::capture_patterns(patterns)?
        .map_filter(|node| {
            let mut key = [0; 32];
            for (chunk, capture) in key.chunks_exact_mut(4).zip(&node.captures) {
                chunk.copy_from_slice(&capture.data);
            }
            if key == *b"\x6f\x16\x80\x73\xb9\xb2\x14\x49\xd7\x42\x24\x17\x00\x06\x8a\xda\xbc\x30\x6f\xa9\xaa\x38\x31\x16\x4d\xee\x8d\xe3\x4e\x0e\xfb\xb0" {
                None
            } else {
                Some(AESKey(key))
            }
        })
        .resolve(ctx)
        .await
        .map(|nodes| Self(nodes.iter().map(|node| AESKey(node.value.0)).collect()))
});

